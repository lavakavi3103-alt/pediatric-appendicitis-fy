import warnings
warnings.filterwarnings("ignore")

import numpy as np
import pandas as pd
from pathlib import Path
from PIL import Image

import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader, WeightedRandomSampler
from torchvision import transforms, models
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, f1_score, roc_auc_score

# ============================================================
# Reproducibility
# ============================================================

torch.manual_seed(42)
np.random.seed(42)

if torch.cuda.is_available():
    torch.cuda.manual_seed_all(42)


# ============================================================
# Paths
# ============================================================

OUT = Path("outputs")
OUT.mkdir(exist_ok=True)

# IMPORTANT:
# ROI images generated by 09g_roi_preprocess.py
IMG_DIR = Path("data/processed/images_roi")

# ROI manifest generated by 09g_roi_preprocess.py
manifest = pd.read_csv(
    "data/processed/image_manifest_roi.csv"
)

# Appendicitis = 1
# Other diagnosis = 0
manifest["label"] = (
    manifest["diagnosis"].str.lower() == "appendicitis"
).astype(int)

print("=" * 60)
print("ROI-BASED CNN TRAINING")
print("=" * 60)

print(f"Total ROI images: {len(manifest)}")
print(f"Total patients: {manifest['patient_id'].nunique()}")

print("\nClass distribution:")
print(manifest["label"].value_counts().sort_index())


# ============================================================
# Patient-level train/test split
# ============================================================

patients = manifest["patient_id"].unique()

train_patients, test_patients = train_test_split(
    patients,
    test_size=0.2,
    random_state=42
)

train_df = manifest[
    manifest["patient_id"].isin(train_patients)
].reset_index(drop=True)

test_df = manifest[
    manifest["patient_id"].isin(test_patients)
].reset_index(drop=True)


print("\n" + "=" * 60)
print("DATA SPLIT")
print("=" * 60)

print(
    f"Train images: {len(train_df)} "
    f"({train_df['patient_id'].nunique()} patients)"
)

print(
    f"Test images: {len(test_df)} "
    f"({test_df['patient_id'].nunique()} patients)"
)

print("\nTrain class distribution:")
print(train_df["label"].value_counts().sort_index())

print("\nTest class distribution:")
print(test_df["label"].value_counts().sort_index())


# ============================================================
# Dataset
# ============================================================

class USDataset(Dataset):

    def __init__(self, df, img_dir, transform):
        self.df = df.reset_index(drop=True)
        self.img_dir = img_dir
        self.transform = transform

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):

        row = self.df.iloc[idx]

        img_path = self.img_dir / row["image_file"]

        img = Image.open(img_path).convert("RGB")

        img = self.transform(img)

        label = torch.tensor(
            row["label"],
            dtype=torch.long
        )

        return img, label


# ============================================================
# Data augmentation
# ============================================================

train_transform = transforms.Compose([

    transforms.RandomHorizontalFlip(
        p=0.5
    ),

    transforms.RandomRotation(
        degrees=15
    ),

    transforms.ColorJitter(
        brightness=0.2,
        contrast=0.2
    ),

    transforms.ToTensor(),

    transforms.Normalize(
        mean=[0.485, 0.456, 0.406],
        std=[0.229, 0.224, 0.225]
    ),
])


test_transform = transforms.Compose([

    transforms.ToTensor(),

    transforms.Normalize(
        mean=[0.485, 0.456, 0.406],
        std=[0.229, 0.224, 0.225]
    ),
])


# ============================================================
# Dataset + DataLoader
# ============================================================

train_ds = USDataset(
    train_df,
    IMG_DIR,
    train_transform
)

test_ds = USDataset(
    test_df,
    IMG_DIR,
    test_transform
)


# ============================================================
# Weighted Random Sampling
# ============================================================

class_counts = (
    train_df["label"]
    .value_counts()
    .sort_index()
)

sample_weights = (
    train_df["label"]
    .map(
        lambda label:
        1.0 / class_counts[label]
    )
    .values
)

sample_weights = torch.DoubleTensor(
    sample_weights
)

sampler = WeightedRandomSampler(
    weights=sample_weights,
    num_samples=len(sample_weights),
    replacement=True
)


# ============================================================
# DataLoaders
# ============================================================

train_loader = DataLoader(
    train_ds,
    batch_size=16,
    sampler=sampler
)

test_loader = DataLoader(
    test_ds,
    batch_size=16,
    shuffle=False
)


# ============================================================
# Device
# ============================================================

device = torch.device(
    "cuda" if torch.cuda.is_available()
    else "cpu"
)

print(
    f"\nUsing device: {device}"
)


# ============================================================
# ResNet18
# ============================================================

model = models.resnet18(
    weights=models.ResNet18_Weights.IMAGENET1K_V1
)


# ============================================================
# Fine-tuning
# ============================================================
#
# layer1, layer2 -> frozen
# layer3, layer4, fc -> trainable
#
# This gives the model more flexibility than the previous
# CNN v2 experiment while still using ImageNet pretrained
# features.
# ============================================================

for name, param in model.named_parameters():

    if (
        "layer3" in name
        or "layer4" in name
        or "fc" in name
    ):
        param.requires_grad = True

    else:
        param.requires_grad = False


# Replace final classification layer

model.fc = nn.Linear(
    model.fc.in_features,
    2
)

model = model.to(device)


# ============================================================
# Loss
# ============================================================

criterion = nn.CrossEntropyLoss()


# ============================================================
# Optimizer
# ============================================================

optimizer = torch.optim.Adam(
    [
        p for p in model.parameters()
        if p.requires_grad
    ],
    lr=3e-4,
    weight_decay=1e-4
)


# ============================================================
# Learning-rate scheduler
# ============================================================

scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
    optimizer,
    mode="min",
    factor=0.5,
    patience=2
)


# ============================================================
# Training
# ============================================================

EPOCHS = 20

print("\n" + "=" * 60)
print("Training ROI CNN")
print("=" * 60)

for epoch in range(EPOCHS):

    model.train()

    total_loss = 0.0

    for imgs, labels in train_loader:

        imgs = imgs.to(device)
        labels = labels.to(device)

        optimizer.zero_grad()

        outputs = model(imgs)

        loss = criterion(
            outputs,
            labels
        )

        loss.backward()

        optimizer.step()

        total_loss += loss.item()


    avg_loss = (
        total_loss /
        len(train_loader)
    )

    scheduler.step(avg_loss)

    current_lr = optimizer.param_groups[0]["lr"]

    print(
        f"Epoch {epoch + 1:02d}/{EPOCHS} "
        f"| Loss: {avg_loss:.4f} "
        f"| LR: {current_lr:.6f}"
    )


# ============================================================
# Image-level evaluation
# ============================================================

model.eval()

all_preds = []
all_labels = []
all_probs = []

with torch.no_grad():

    for imgs, labels in test_loader:

        imgs = imgs.to(device)

        outputs = model(imgs)

        probs = torch.softmax(
            outputs,
            dim=1
        )[:, 1]

        preds = outputs.argmax(
            dim=1
        )

        all_preds.extend(
            preds.cpu().numpy()
        )

        all_labels.extend(
            labels.numpy()
        )

        all_probs.extend(
            probs.cpu().numpy()
        )


# ============================================================
# Metrics
# ============================================================

acc = accuracy_score(
    all_labels,
    all_preds
)

f1 = f1_score(
    all_labels,
    all_preds,
    zero_division=0
)

auc = roc_auc_score(
    all_labels,
    all_probs
)


print("\n" + "=" * 60)
print("ROI CNN - IMAGE LEVEL RESULTS")
print("=" * 60)

print(
    f"Accuracy : {acc:.4f}"
)

print(
    f"F1 Score : {f1:.4f}"
)

print(
    f"AUC      : {auc:.4f}"
)


# ============================================================
# Patient-level evaluation
# ============================================================

test_results = test_df.copy()

test_results["pred_prob"] = all_probs


patient_results = (
    test_results
    .groupby("patient_id")
    .agg(
        label=("label", "first"),
        avg_prob=("pred_prob", "mean")
    )
    .reset_index()
)


patient_results["pred"] = (
    patient_results["avg_prob"] > 0.5
).astype(int)


p_acc = accuracy_score(
    patient_results["label"],
    patient_results["pred"]
)

p_f1 = f1_score(
    patient_results["label"],
    patient_results["pred"],
    zero_division=0
)

p_auc = roc_auc_score(
    patient_results["label"],
    patient_results["avg_prob"]
)


print("\n" + "=" * 60)
print("ROI CNN - PATIENT LEVEL RESULTS")
print("=" * 60)

print(
    f"Accuracy : {p_acc:.4f}"
)

print(
    f"F1 Score : {p_f1:.4f}"
)

print(
    f"AUC      : {p_auc:.4f}"
)


# ============================================================
# Save model
# ============================================================

model_path = (
    OUT / "cnn_roi_model.pth"
)

torch.save(
    model.state_dict(),
    model_path
)

print(
    f"\nSaved model: {model_path}"
)


# ============================================================
# Save results
# ============================================================

results = pd.DataFrame([

    {
        "name": "ROI CNN (image-level)",
        "accuracy": acc,
        "f1": f1,
        "auc": auc
    },

    {
        "name": "ROI CNN (patient-level, avg)",
        "accuracy": p_acc,
        "f1": p_f1,
        "auc": p_auc
    }

])


results_path = (
    OUT /
    "phase3_roi_cnn_results.csv"
)

results.to_csv(
    results_path,
    index=False
)

print(
    f"Saved results: {results_path}"
)

print("\nROI CNN training completed successfully.")